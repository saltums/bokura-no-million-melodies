def gen():
    out = []; seen = set()
    for fi, (kind, mood, era, text, slots) in enumerate(TPL):
        keys = sorted({k for k in P if '{' + k + '}' in text})
        pools = [P[k] for k in keys]
        combos = list(itertools.product(*pools)) if pools else [()]
        R.shuffle(combos)
        for c in combos[:60]:
            t = text
            for k, v in zip(keys, c): t = t.replace('{' + k + '}', v, 1) if t.count('{' + k + '}') == 1 else t.replace('{' + k + '}', v)
            if t in seen or '"' in t: continue
            seen.add(t); out.append({"t": t, "k": kind, "m": mood, "e": era, "f": fi})
    return out

